# Python Basics

# 1. Print
print("Hello Python")

# 2. Variables
name = "Gaurav"
age = 18

print(name)
print(age)

# 3. Input
num = int(input("Enter a number: "))

# 4. Even or Odd
if num % 2 == 0:
    print("Even")
else:
    print("Odd")

# 5. For Loop
for i in range(1, 11):
    print(i)

# 6. While Loop
i = 1
while i <= 5:
    print(i)
    i += 1